using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;

namespace GameApiExporter
{
    public static class RuntimeApiExporter
    {
        private static bool hasExported;

        public static void TryExportOnStartup()
        {
            if (hasExported)
            {
                return;
            }

            hasExported = true;

            var config = ModConfig.Instance;
            if (!config.Enabled || !config.RuntimeApiExportOnStartup)
            {
                SafeLog("Runtime API export skipped by config");
                return;
            }

            try
            {
                string exportRoot = PrepareExportDirectory(config.ExportDirectoryName);
                string readmePath = Path.Combine(exportRoot, "README.md");
                var summaryLines = new List<string>
                {
                    "# Runtime API Export",
                    "",
                    "Generated by `GameApiExporter` from the live 7 Days to Die process.",
                    "",
                    $"Timestamp (UTC): {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss}",
                    ""
                };

                int exportedAssemblyCount = 0;
                foreach (string assemblyName in ParseAssemblyNames(config.TargetAssemblies))
                {
                    Assembly assembly = ResolveAssembly(assemblyName);
                    if (assembly == null)
                    {
                        summaryLines.Add($"- `{assemblyName}`: not found in current AppDomain");
                        continue;
                    }

                    var export = ExportAssembly(assembly);
                    string safeAssemblyName = SanitizeFileName(assembly.GetName().Name ?? assemblyName);
                    string exportFilePath = Path.Combine(exportRoot, safeAssemblyName + ".txt");
                    File.WriteAllLines(exportFilePath, export.Lines, Encoding.UTF8);

                    summaryLines.Add($"- `{assembly.GetName().Name}`: {export.PublicTypeCount} public types, {export.FieldCount} fields, {export.PropertyCount} properties, {export.MethodCount} methods");
                    summaryLines.Add($"  - File: `{Path.GetFileName(exportFilePath)}`");

                    exportedAssemblyCount++;
                }

                File.WriteAllLines(readmePath, summaryLines, Encoding.UTF8);
                SafeLog($"Runtime API export completed: {exportedAssemblyCount} assemblies -> {exportRoot}");
            }
            catch (Exception ex)
            {
                SafeLog($"Runtime API export failed: {ex.Message}");
                SafeLog(ex.StackTrace ?? "(no stack trace)");
            }
        }

        private static ExportResult ExportAssembly(Assembly assembly)
        {
            var result = new ExportResult();
            var lines = new List<string>();
            Type[] types = GetLoadableTypes(assembly);

            foreach (Type type in types
                .Where(t => t != null && !string.IsNullOrEmpty(t.FullName))
                .Where(t => t.IsPublic || t.IsNestedPublic)
                .Where(t => !t.Name.StartsWith("<", StringComparison.Ordinal))
                .OrderBy(t => t.Namespace)
                .ThenBy(t => t.FullName))
            {
                string baseTypeName = "";
                try
                {
                    if (type.BaseType != null)
                    {
                        baseTypeName = type.BaseType.FullName ?? "";
                    }
                }
                catch
                {
                    baseTypeName = "";
                }

                lines.Add(string.Join("\t", "T", type.FullName, type.Namespace ?? "", baseTypeName));
                result.PublicTypeCount++;

                foreach (FieldInfo field in type
                    .GetFields(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly)
                    .OrderBy(f => f.Name))
                {
                    lines.Add(string.Join("\t", "F", type.FullName, GetFriendlyTypeName(field.FieldType), field.Name));
                    result.FieldCount++;
                }

                foreach (PropertyInfo property in type
                    .GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly)
                    .OrderBy(p => p.Name))
                {
                    lines.Add(string.Join("\t", "P", type.FullName, GetFriendlyTypeName(property.PropertyType), property.Name, property.CanRead, property.CanWrite));
                    result.PropertyCount++;
                }

                foreach (MethodInfo method in type
                    .GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly)
                    .Where(m => !m.IsSpecialName)
                    .OrderBy(m => m.Name))
                {
                    string parameterSignature = string.Join(", ", method
                        .GetParameters()
                        .Select(p => GetFriendlyTypeName(p.ParameterType) + " " + p.Name));
                    lines.Add(string.Join("\t", "M", type.FullName, GetFriendlyTypeName(method.ReturnType), method.Name, parameterSignature));
                    result.MethodCount++;
                }
            }

            result.Lines = lines;
            return result;
        }

        private static Type[] GetLoadableTypes(Assembly assembly)
        {
            try
            {
                return assembly.GetTypes();
            }
            catch (ReflectionTypeLoadException rtle)
            {
                return rtle.Types.Where(t => t != null).ToArray();
            }
        }

        private static IEnumerable<string> ParseAssemblyNames(string configuredNames)
        {
            if (string.IsNullOrWhiteSpace(configuredNames))
            {
                yield break;
            }

            foreach (string name in configuredNames.Split(','))
            {
                string trimmed = name.Trim();
                if (!string.IsNullOrWhiteSpace(trimmed))
                {
                    yield return trimmed;
                }
            }
        }

        private static Assembly ResolveAssembly(string assemblyName)
        {
            Assembly loaded = AppDomain.CurrentDomain
                .GetAssemblies()
                .FirstOrDefault(a => string.Equals(a.GetName().Name, assemblyName, StringComparison.OrdinalIgnoreCase));

            if (loaded != null)
            {
                return loaded;
            }

            try
            {
                return Assembly.Load(assemblyName);
            }
            catch
            {
                return null;
            }
        }

        private static string PrepareExportDirectory(string exportDirectoryName)
        {
            string localLow = Path.GetFullPath(Path.Combine(
                Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData),
                "..",
                "LocalLow",
                "The Fun Pimps",
                "7 Days To Die",
                "Mods",
                "GameApiExporter"));

            string directoryName = string.IsNullOrWhiteSpace(exportDirectoryName) ? "api-export" : exportDirectoryName.Trim();
            string exportRoot = Path.Combine(localLow, directoryName, "latest");

            if (Directory.Exists(exportRoot))
            {
                Directory.Delete(exportRoot, true);
            }

            Directory.CreateDirectory(exportRoot);
            return exportRoot;
        }

        private static string GetFriendlyTypeName(Type type)
        {
            if (type == null)
            {
                return "";
            }

            if (!type.IsGenericType)
            {
                return type.FullName ?? type.Name;
            }

            string genericTypeName = type.GetGenericTypeDefinition().FullName ?? type.Name;
            int tickIndex = genericTypeName.IndexOf('`');
            if (tickIndex >= 0)
            {
                genericTypeName = genericTypeName.Substring(0, tickIndex);
            }

            string genericArgs = string.Join(", ", type.GetGenericArguments().Select(GetFriendlyTypeName));
            return genericTypeName + "<" + genericArgs + ">";
        }

        private static string SanitizeFileName(string name)
        {
            var builder = new StringBuilder(name.Length);
            foreach (char c in name)
            {
                builder.Append(Path.GetInvalidFileNameChars().Contains(c) ? '_' : c);
            }

            return builder.ToString();
        }

        private static void SafeLog(string message)
        {
            try
            {
                UnityEngine.Debug.Log("[GameApiExporter] " + message);
            }
            catch
            {
                // Unity not available
            }
        }

        private class ExportResult
        {
            public List<string> Lines { get; set; }
            public int PublicTypeCount { get; set; }
            public int FieldCount { get; set; }
            public int PropertyCount { get; set; }
            public int MethodCount { get; set; }
        }
    }
}
